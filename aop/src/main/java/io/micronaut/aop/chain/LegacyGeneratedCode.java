package io.micronaut.aop.chain;

import io.micronaut.core.annotation.Internal;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Warns that an entry point kept for code generated by an earlier version was called, once per entry point and target.
 *
 * @since 5.3.0
 */
@Internal
final class LegacyGeneratedCode {
    private static final Logger LOG = LoggerFactory.getLogger(LegacyGeneratedCode.class);
    private static final Set<String> WARNED = ConcurrentHashMap.newKeySet();
    private static final Set<String> ENTRY_POINT_CLASSES = Set.of(
        LegacyGeneratedCode.class.getName(),
        InterceptorChain.class.getName(),
        ConstructorInterceptorChain.class.getName(),
        MethodInterceptorChain.class.getName()
    );
    private static final StackWalker STACK_WALKER = StackWalker.getInstance();

    private LegacyGeneratedCode() {
    }

    /**
     * Logs a warning the first time the entry point is called for the given target.
     *
     * @param entryPoint The class and method called, as {@code Class.method}
     * @param target The type and member the generated code was compiled for, as {@code Type#member}
     */
    static void warn(String entryPoint, String target) {
        if (WARNED.add(entryPoint + ' ' + target)) {
            String caller = callerClassName();
            LOG.warn("{} was called for {} by {}, which was compiled with a Micronaut version before 5.3. Recompile the "
                + "module containing {} with Micronaut 5.3 or later; this entry point will be removed in a future release.",
                entryPoint, target, caller, caller);
        }
    }

    /**
     * Describes a method as {@code Type#method}.
     *
     * @param declaringType The type that declares the method
     * @param methodName The method name
     * @return The description
     */
    static String describe(Class<?> declaringType, String methodName) {
        return declaringType.getName() + '#' + methodName;
    }

    private static String callerClassName() {
        return STACK_WALKER.walk(frames -> frames
            .map(StackWalker.StackFrame::getClassName)
            .dropWhile(ENTRY_POINT_CLASSES::contains)
            .findFirst()
            .orElse("unknown"));
    }
}
